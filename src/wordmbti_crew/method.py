_OPP = {"T": "F", "F": "T", "S": "N", "N": "S"}


def opp(f: str) -> str:
    return _OPP[f[0]] + ("e" if f[1] == "i" else "i")


def stack_of(pair: str) -> list[str]:
    """主导、辅助、第三位、劣势，例如 Ti-Ne -> [Ti, Ne, Fi, Fe]"""
    d, a = pair.split("-")
    return [d, a, opp(a), opp(d)]


